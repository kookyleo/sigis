//! Fixture loaders shared by the integration tests.

#![allow(dead_code)]

use std::path::PathBuf;

use base64::Engine;
use hanko_certvalidator::Cert;
use hanko_core::time::Moment;

/// Path of a pyhanko-certvalidator fixture.
pub fn fixture(parts: &[&str]) -> PathBuf {
    hanko_testdata::certvalidator(parts)
}

/// Read a fixture file.
pub fn read(parts: &[&str]) -> Vec<u8> {
    let path = fixture(parts);
    std::fs::read(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()))
}

/// Load a PEM or DER certificate (`load_cert_object`).
pub fn load_cert(parts: &[&str]) -> Cert {
    Cert::from_pem_or_der(&read(parts)).unwrap_or_else(|e| panic!("parse {parts:?}: {e}"))
}

/// Load a NIST PKITS certificate.
pub fn load_nist_cert(name: &str) -> Cert {
    load_cert(&["nist_pkits", "certs", name])
}

/// Load a NIST PKITS CRL (DER).
pub fn load_nist_crl(name: &str) -> Vec<u8> {
    read(&["nist_pkits", "crls", name])
}

/// Load a base64-encoded OpenSSL OCSP response (`load_openssl_ors`).
pub fn load_openssl_ors(name: &str) -> Vec<u8> {
    let text: String = String::from_utf8(read(&["openssl-ocsp", name]))
        .expect("utf-8")
        .split_whitespace()
        .collect();
    base64::engine::general_purpose::STANDARD
        .decode(text)
        .expect("base64")
}

/// A certificate generated by `tests/data/sigis-generated/generate.sh`.
pub fn load_generated_cert(name: &str) -> Cert {
    let path = hanko_testdata::path(&["sigis-generated", name]);
    Cert::from_pem_or_der(&std::fs::read(&path).expect("read")).expect("parse")
}

/// Parse an RFC 3339 UTC timestamp.
pub fn moment(s: &str) -> Moment {
    Moment::parse_rfc3339(s).unwrap_or_else(|| panic!("bad moment {s}"))
}

/// The time NIST PKITS tests are frozen at (`freeze_time('2022-05-01')`).
pub fn pkits_moment() -> Moment {
    moment("2022-05-01T00:00:00Z")
}

/// In-memory fetchers for tests (`MockOCSPFetcher`, `MockCRLFetcher`,
/// `MockCertFetcher`, `ReturnPredeterminedCRLs` of the upstream tests).
pub mod fakes {
    use std::sync::atomic::{AtomicUsize, Ordering};
    use std::sync::Arc;

    use hanko_certvalidator::Cert;
    use hanko_core::errors::{FetchError, FetchErrorKind};
    use hanko_core::fetch::{CertificateFetcher, CrlFetcher, Fetchers, OcspFetcher};

    /// Fails every request, counting calls.
    #[derive(Debug, Default)]
    pub struct Failing {
        pub calls: AtomicUsize,
    }

    impl Failing {
        fn fail(&self) -> FetchError {
            self.calls.fetch_add(1, Ordering::SeqCst);
            FetchError::new(FetchErrorKind::Network, "No connection")
        }
    }

    impl OcspFetcher for Failing {
        fn fetch_ocsp(&self, _: &Cert, _: &Cert) -> Result<Vec<u8>, FetchError> {
            Err(self.fail())
        }
    }

    impl CrlFetcher for Failing {
        fn fetch_crls(&self, _: &Cert) -> Result<Vec<Vec<u8>>, FetchError> {
            Err(self.fail())
        }
    }

    impl CertificateFetcher for Failing {
        fn fetch_issuers(&self, _: &Cert) -> Result<Vec<Cert>, FetchError> {
            Err(self.fail())
        }
    }

    /// Returns the same CRLs for every certificate.
    #[derive(Debug)]
    pub struct FixedCrls(pub Vec<Vec<u8>>, pub AtomicUsize);

    impl CrlFetcher for FixedCrls {
        fn fetch_crls(&self, _: &Cert) -> Result<Vec<Vec<u8>>, FetchError> {
            self.1.fetch_add(1, Ordering::SeqCst);
            Ok(self.0.clone())
        }
    }

    /// Returns the same certificates as issuers of every certificate.
    #[derive(Debug)]
    pub struct FixedIssuers(pub Vec<Cert>);

    impl CertificateFetcher for FixedIssuers {
        fn fetch_issuers(&self, _: &Cert) -> Result<Vec<Cert>, FetchError> {
            Ok(self.0.clone())
        }
    }

    /// Fetchers that fail, except for the given CRL fetcher.
    pub fn with_crls(crl: Arc<dyn CrlFetcher>) -> Fetchers {
        Fetchers {
            ocsp: Some(Arc::new(Failing::default())),
            crl: Some(crl),
            cert: Some(Arc::new(Failing::default())),
        }
    }
}
