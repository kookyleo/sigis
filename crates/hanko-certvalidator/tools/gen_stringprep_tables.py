"""Generate src/stringprep_tables.rs from Python's `stringprep` module.

asn1crypto prepares directory string values with RFC 4518 / RFC 3454
string preparation (Unicode 3.2 tables) and raises on prohibited or
malformed values. pyhanko-certvalidator inherits that behaviour, so the port
uses the same tables. Run with any Python 3:

    python3 tools/gen_stringprep_tables.py > src/stringprep_tables.rs
"""

import stringprep
import sys

TABLES = {
    'A1': stringprep.in_table_a1,
    'C3': stringprep.in_table_c3,
    'C4': stringprep.in_table_c4,
    'C5': stringprep.in_table_c5,
    'C8': stringprep.in_table_c8,
    'D1': stringprep.in_table_d1,
    'D2': stringprep.in_table_d2,
}


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        try:
            ch = chr(cp)
            hit = pred(ch)
        except ValueError:
            hit = False
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


print('// @generated by tools/gen_stringprep_tables.py from Python stringprep')
print('// (RFC 3454 tables, Unicode 3.2). Do not edit.')
print()
print('//! RFC 3454 tables used by [`crate::names`].')
print()
for name, pred in TABLES.items():
    rs = ranges(pred)
    print(f'/// RFC 3454 table {name[0]}.{name[1:]} as inclusive code point ranges.')
    print(f'pub(crate) static {name}: &[(u32, u32)] = &[')
    for a, b in rs:
        print(f'    (0x{a:04X}, 0x{b:04X}),')
    print('];')
    print()
